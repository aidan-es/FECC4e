pub fn get_v3_asset_name(asset_type: AssetType, mut index: usize) -> Option<&'static str> {
    if index == 0 {
        return None;
    }
    index -= 1;
    match asset_type {
        AssetType::Face => V3_FACES.get(index).copied(),
        AssetType::Armour => V3_ARMOUR.get(index).copied(),
        AssetType::Hair => V3_HAIR.get(index).copied(),
        AssetType::Accessory => V3_ACCESSORIES.get(index).copied(),
        AssetType::Token => V3_TOKENS.get(index).copied(),
        _ => None,
    }
}
